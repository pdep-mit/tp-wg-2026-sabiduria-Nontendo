# Sprite sencillo de un slime, en una grilla de pixeles de 3 x 3.
Add-Type -AssemblyName System.Drawing
$sprite = New-Object System.Drawing.Bitmap 48, 48
$lienzo = [System.Drawing.Graphics]::FromImage($sprite)
$lienzo.Clear([System.Drawing.Color]::Transparent)
$contorno = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 72, 28, 58))
$cuerpo = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 185, 62, 96))
$brillo = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 244, 125, 142))
$ojos = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::FromArgb(255, 255, 239, 211))
$lienzo.FillRectangle($contorno, 9, 15, 30, 24)
$lienzo.FillRectangle($contorno, 3, 24, 42, 18)
$lienzo.FillRectangle($contorno, 15, 9, 18, 6)
$lienzo.FillRectangle($cuerpo, 12, 18, 24, 21)
$lienzo.FillRectangle($cuerpo, 6, 27, 36, 12)
$lienzo.FillRectangle($cuerpo, 18, 12, 12, 6)
$lienzo.FillRectangle($brillo, 15, 18, 9, 3)
$lienzo.FillRectangle($ojos, 12, 27, 6, 6)
$lienzo.FillRectangle($ojos, 30, 27, 6, 6)
$lienzo.FillRectangle($contorno, 21, 33, 6, 3)
$sprite.Save((Join-Path $PSScriptRoot '../assets/zelda/enemigo.png'), [System.Drawing.Imaging.ImageFormat]::Png)
$lienzo.Dispose()
$sprite.Dispose()
$contorno.Dispose()
$cuerpo.Dispose()
$brillo.Dispose()
$ojos.Dispose()
